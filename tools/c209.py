    for eid,title,when,reg,ov,a,b,_,_n in R:
        if "('%s',"%eid in txt: print("skip",eid); continue
        rel=[a,b]+EXTRA.get(eid,[])
        s=srcs(*rel)
        T.append((eid,title,"风格","comparative",when,reg,"综合","重要",ov,when,ov,",".join(rel),",".join(s)))
    close=max(i for i,l in enumerate(lines) if l.strip()=="]")
    lines[close:close]=["(%s),"%",\n ".join(repr(x) for x in t) for t in T]
    io.open(p,"w",encoding="utf-8").write("\n".join(lines)); print("catalog appended",len(T))
